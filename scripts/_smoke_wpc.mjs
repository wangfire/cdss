import crypto from 'node:crypto';
import fs from 'node:fs';
const settings = JSON.parse(fs.readFileSync('src/HospitalAi.Api/appsettings.Development.json', 'utf8'));
const key = settings.JwtAuth.Key;
const hospitalId = '6b427cb5-a6ba-4a8e-9b36-311c1102f20b';
const b64 = (v) => Buffer.from(typeof v === 'string' ? v : JSON.stringify(v)).toString('base64url');
const now = Math.floor(Date.now() / 1000);
const header = b64({ alg: 'HS256', typ: 'JWT' });
const payload = b64({ sub: 'smoke-wpc', nameid: 'smoke-wpc', iss: 'hospitalai', aud: 'hospitalai-admin', iat: now, nbf: now - 30, exp: now + 7200, hospitalId, 'http://schemas.microsoft.com/ws/2008/06/identity/claims/role': 'ADMIN' });
const sig = crypto.createHmac('sha256', key).update(`${header}.${payload}`).digest('base64url');
const token = `${header}.${payload}.${sig}`;
const rowId = '3EEFEAAE-F134-42F8-80F1-F7C7B4AB0DDC';
const resp = await fetch(`http://127.0.0.1:5081/api/v1/knowledge/icd-index/${rowId}/enabled`, { method: 'PATCH', headers: { Authorization: `Bearer ${token}`, 'X-Hospital-Id': hospitalId, 'Content-Type': 'application/json' }, body: JSON.stringify({ enabled: true }) });
console.log('PATCH:', resp.status, (await resp.text()).slice(0, 160));